/** JupiterZ RFQ snapshot for the stock registry (docs/JUPITERZ.md). Market makers quote some stocks whose on-chain pools are too thin to trade (Ondo on Solana: a few
 *  hundred dollars of pool liquidity, firm maker quotes at $10k). The registry's `tradable` comes from a 0.05 SOL pool route, so it misses them. This asks JupiterZ alone
 *  (excludeRouters=metis,dflow,okx, no taker: a quote, nothing built or signed) for a $1,000 USDC buy of every registered stock with a share price, and keeps the ones whose
 *  price per share (with the mint's multiplier) is at most 3% above the share price: the same limit as the server's fill-price check.
 *  usage: npm run stocks:rfq   (about 40 minutes for every issuer at one call a second, RFQ_PACE_MS; JUPITER_API_KEY optional; SOL_RPC_URL optional; RFQ_ISSUERS=on,x,bp narrows the run)
 *  Writes packages/sol/src/rfqlist.generated.ts. A listing hint only: every RFQ fill is re-checked live (gateRfq, simulation, rfqFillCheck). */
import { writeFileSync } from 'node:fs';
import { GuardedRpc } from './solreadonly.ts';
import { STOCKS_SOLANA, readStockStates } from '../../sol/src/index.ts';

const USDC = 'EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v', USD = 1000, MAX_DEV = 3;
const KEY = process.env.JUPITER_API_KEY, BASE = KEY ? 'https://api.jup.ag' : 'https://lite-api.jup.ag', H: Record<string, string> = KEY ? { 'x-api-key': KEY } : {};
const PACE = Number(process.env.RFQ_PACE_MS ?? 1100);   // about one call a second, keyed or not: the API key is shared with the server and the desk, and a faster run used up its quota
const CODES: Record<string, string> = { x: 'Backed (xStocks)', on: 'Ondo Global Markets', bp: 'Backpack Securities' };
const issuers = (process.env.RFQ_ISSUERS ?? 'x,on,bp').split(',').map(s => CODES[s.trim()]).filter(Boolean);
const rpc = new GuardedRpc(process.env.SOL_RPC_URL ?? 'https://api.mainnet-beta.solana.com'), sleep = (ms: number) => new Promise(r => setTimeout(r, ms));
async function getJson(url: string, tries = 4): Promise<any> {
  for (let i = 0; ; i++) { const r = await fetch(url, { headers: H, signal: AbortSignal.timeout(15_000) }).catch(() => undefined);
    if (r && r.status !== 429 && r.status < 500) return r.json().catch(() => ({})); if (i >= tries) return {}; await sleep(1500 * 2 ** i); }
}

const cands = STOCKS_SOLANA.filter(a => issuers.includes(a.issuer));
// 1. share prices (50 ids per call): only stocks with an underlying share price can be checked
const share = new Map<string, number>();
for (let i = 0; i < cands.length; i += 50) { const ids = cands.slice(i, i + 50).map(a => a.mint); const j = await getJson(`${BASE}/price/v3?ids=${ids.join(',')}`); await sleep(PACE);
  for (const id of ids) { const p = Number(j?.[id]?.stockData?.price); if (p > 0) share.set(id, p); } }
const priced = cands.filter(a => share.has(a.mint));
// 2. the multiplier of each priced mint (one token = multiplier x one share)
const mult = new Map<string, number>();
for (let i = 0; i < priced.length; i += 100) { const st = await readStockStates(rpc as any, priced.slice(i, i + 100).map(a => a.mint)); for (const [m, s] of st) mult.set(m, Number(s.multiplier)); }
// 3. a JupiterZ-only quote for a $1,000 USDC buy
const rows: [string, number][] = []; let quoted = 0, done = 0;
for (const a of priced) {
  const j = await getJson(`${BASE}/swap/v2/order?inputMint=${USDC}&outputMint=${a.mint}&amount=${USD * 1e6}&excludeRouters=metis,dflow,okx`); await sleep(PACE);
  if (++done % 50 === 0) console.log(`${done}/${priced.length} asked, ${quoted} quoted`);
  const out = Number(j?.outAmount ?? 0), m = mult.get(a.mint); if (j?.router !== 'jupiterz' || !(out > 0) || !(m && m > 0)) continue; quoted++;
  const perShare = USD / (out / 10 ** a.decimals * m), dev = Math.round((perShare / share.get(a.mint)! - 1) * 10_000) / 100;
  if (dev <= MAX_DEV) rows.push([a.mint, dev]);
}
const at = new Date().toISOString(), meta = { generatedAt: at, usd: USD, maxDeviationPct: MAX_DEV, issuers, asked: priced.length, unpriced: cands.length - priced.length, quoted, listed: rows.length };
writeFileSync('packages/sol/src/rfqlist.generated.ts', `/** GENERATED by packages/live/src/rfqregistry.ts (npm run stocks:rfq) on ${at}. Do not edit by hand: run it again.
 *  Registered stocks that JupiterZ market makers quoted for a $${USD.toLocaleString('en-US')} USDC buy at most ${MAX_DEV}% above the share price, with that deviation in percent. A snapshot for listings. */
export const RFQ_LIST_META = ${JSON.stringify(meta)} as const;
export const RFQ_LIST: readonly (readonly [string, number])[] = [
${rows.sort((p, q) => p[0].localeCompare(q[0])).map(r => `  ${JSON.stringify(r)},`).join('\n')}
];
`);
console.log(`wrote ${rows.length} RFQ-quoted stocks (of ${priced.length} with a share price, ${quoted} quoted) to packages/sol/src/rfqlist.generated.ts`);
